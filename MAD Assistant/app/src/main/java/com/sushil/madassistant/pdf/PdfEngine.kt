package com.sushil.madassistant.pdf

import android.content.Context
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import com.sushil.madassistant.data.db.MadDatabase
import com.sushil.madassistant.data.db.WorkRecordEntity
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object PdfEngine {

    suspend fun generateWorkListPdf(
        context: Context,
        db: MadDatabase,
        record: WorkRecordEntity
    ): File? {
        return try {
            val items = db.workRecordDao().getWorkRecordItems(record.id)
            if (items.isEmpty()) return null

            val customer = db.customerDao().getCustomerById(record.customerId)
            val tech = db.technicianDao().getProfile()

            fun sanitize(s: String): String =
                s.replace(Regex("[\\\\/:*?\"<>|]"), "_").replace(" ", "_")

            val fileName = sanitize(customer?.name ?: "Customer") + "_" +
                    sanitize(record.category) + "_" + sanitize(record.subcategory) + ".pdf"

            val dir = File(context.filesDir, "pdf")
            if (!dir.exists()) dir.mkdirs()
            val file = File(dir, fileName)

            val doc = PdfDocument()
            val pageWidth = 595
            val pageHeight = 842
            val margin = 40f

            val titleP = Paint().apply {
                color = Color.rgb(10, 30, 60); textSize = 16f
                typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
                isAntiAlias = true
            }
            val headP = Paint().apply {
                color = Color.rgb(10, 30, 60); textSize = 12f
                typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
                isAntiAlias = true
            }
            val bodyP = Paint().apply { color = Color.BLACK; textSize = 10f; isAntiAlias = true }
            val greyP = Paint().apply { color = Color.GRAY; textSize = 8.5f; isAntiAlias = true }
            val lineP = Paint().apply { color = Color.LTGRAY; strokeWidth = 1f }

            var pageNo = 1
            var page = doc.startPage(PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNo).create())
            var canvas = page.canvas
            var y = margin + 10f

            fun newPage() {
                doc.finishPage(page)
                pageNo++
                page = doc.startPage(PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNo).create())
                canvas = page.canvas
                y = margin + 10f
            }

            fun drawText(t: String, x: Float, paint: Paint) {
                canvas.drawText(t, x, y, paint)
            }

            fun ensure(h: Float) {
                if (y + h > pageHeight - margin) newPage()
            }

            drawText("RAJAT ELECTRO-MECH SOLUTIONS (REMS)", margin, titleP); y += 18f
            drawText((tech?.name ?: "") + " - " + (tech?.mobile ?: ""), margin, greyP); y += 13f
            canvas.drawLine(margin, y, pageWidth - margin, y, lineP); y += 18f

            drawText("Customer: " + (customer?.name ?: "") +
                    (if (customer != null && customer.fatherName.isNotBlank()) " (पिता: " + customer.fatherName + ")" else ""),
                margin, headP); y += 14f
            drawText("Mobile: " + (customer?.mobile ?: "") + " - Address: " + (customer?.address ?: ""),
                margin, bodyP); y += 14f
            drawText("Work: " + record.workType + " > " + record.category +
                    (if (record.subcategory.isNotBlank()) " > " + record.subcategory else "") +
                    " - Date: " + record.date, margin, bodyP); y += 16f
            canvas.drawLine(margin, y, pageWidth - margin, y, lineP); y += 18f

            drawText("S.No", margin, headP)
            drawText("Material", margin + 45f, headP)
            drawText("Qty", margin + 300f, headP)
            drawText("Unit", margin + 370f, headP)
            drawText("Remark", margin + 435f, headP)
            y += 6f
            canvas.drawLine(margin, y, pageWidth - margin, y, lineP); y += 15f

            items.forEachIndexed { i, item ->
                ensure(16f)
                drawText((i + 1).toString(), margin, bodyP)
                drawText(item.itemName.take(40), margin + 45f, bodyP)
                drawText(item.quantity.take(12), margin + 300f, bodyP)
                drawText(item.unit.take(10), margin + 370f, bodyP)
                drawText(item.remark.take(28), margin + 435f, greyP)
                y += 16f
            }

            canvas.drawLine(margin, y, pageWidth - margin, y, lineP); y += 16f
            drawText("Generated by MAD Assistant - " +
                    SimpleDateFormat("dd/MM/yyyy HH:mm", Locale.getDefault()).format(Date()),
                margin, greyP)

            doc.finishPage(page)
            FileOutputStream(file).use { doc.writeTo(it) }
            doc.close()
            file
        } catch (e: Exception) {
            e.printStackTrace()
            null
        }
    }
}
